"""Turns the manuals and changelogs of one program (a checkout at its release tag) into Zola content.

Usage: docs.py <checkout> <repo> <tag> <content dir> <static dir>

- docs/manual/{de,en}.md become content/handbuch/<repo>/: the section page holds the introduction, every chapter
  (a "## " heading) is a page of its own, German and English as translations.
- CHANGELOG.md and CHANGELOG.en.md become content/aenderungen/<repo>.md and .en.md.
- Every heading keeps the anchor GitHub gives it, so links into the documents still work. Links within the manual
  point to the chapter page, links to the README and the changelog to the site's pages, other relative links to the
  file on GitHub at the release tag, and images are copied to static/handbuch-bilder/<repo>/.
"""

import posixpath
import re
import shutil
import sys
import unicodedata
from pathlib import Path

GITHUB = "https://github.com/HenryJobst"
LANGS = ("de", "en")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
MD_LINK = re.compile(r"(\]\()([^)\s]+)(\))")
HTML_LINK = re.compile(r'((?:href|src)=")([^"]+)(")')


def plain(text: str) -> str:
    """The text of a heading as GitHub renders it: links to their text, no code ticks or emphasis."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text)
    return text.replace("`", "").replace("*", "")


def slug(text: str) -> str:
    """GitHub's heading anchor: lower case, letters, digits, '-' and '_' kept, spaces to '-'."""
    text = unicodedata.normalize("NFC", plain(text)).strip().lower()
    text = "".join(c for c in text if c.isalnum() or c in "-_ ")
    return text.replace(" ", "-")


def lines_outside_code(lines: list[str]):
    """Yields (index, line, in_code) for every line."""
    in_code = False
    for i, line in enumerate(lines):
        if FENCE.match(line):
            yield i, line, True
            in_code = not in_code
            continue
        yield i, line, in_code


def anchors(lines: list[str]) -> dict[int, str]:
    """The anchor of each heading line, numbered as GitHub numbers repeated headings."""
    seen: dict[str, int] = {}
    found = {}
    for i, line, in_code in lines_outside_code(lines):
        m = HEADING.match(line)
        if in_code or not m:
            continue
        base = slug(m[2])
        n = seen.get(base, 0)
        seen[base] = n + 1
        found[i] = base if n == 0 else f"{base}-{n}"
    return found


class Manual:
    """One language of a manual, split into its introduction and chapters."""

    def __init__(self, path: Path, lang: str):
        self.lang = lang
        self.lines = path.read_text(encoding="utf-8").splitlines()
        self.anchor_of = anchors(self.lines)
        level2 = [i for i, a in self.anchor_of.items() if self.lines[i].startswith("## ")]
        # The table of contents is generated by the site.
        self.toc = {i for i in level2 if slug(self.lines[i][3:]) in ("inhalt", "contents", "table-of-contents")}
        self.starts = [i for i in level2 if i not in self.toc]
        self.title = HEADING.match(self.lines[0])[2] if self.lines and self.lines[0].startswith("# ") else ""
        # anchor -> chapter number (0: the introduction)
        self.chapter_of: dict[str, int] = {}
        for i, a in self.anchor_of.items():
            self.chapter_of[a] = sum(1 for s in self.starts if s <= i)

    def chapters(self) -> list[tuple[str, str, list[str]]]:
        """(title, anchor, body lines) of each chapter."""
        out = []
        for k, start in enumerate(self.starts):
            end = self.starts[k + 1] if k + 1 < len(self.starts) else len(self.lines)
            end = min([e for e in sorted(self.toc) if e > start] + [end])
            out.append((HEADING.match(self.lines[start])[2], self.anchor_of[start], list(range(start + 1, end))))
        return out

    def intro(self) -> list[int]:
        end = min(self.starts + sorted(self.toc) + [len(self.lines)])
        return [i for i in range(1, end) if not self.lines[i].startswith("[")]


class Docs:
    def __init__(self, checkout: Path, repo: str, tag: str, content: Path, static: Path):
        self.checkout, self.repo, self.tag = checkout, repo, tag
        self.content, self.static = content, static
        self.manuals = {lang: Manual(checkout / "docs/manual" / f"{lang}.md", lang) for lang in LANGS}

    def page(self, lang: str, chapter: int) -> str:
        suffix = "" if lang == "de" else ".en"
        if chapter == 0:
            return f"@/handbuch/{self.repo}/_index{suffix}.md"
        return f"@/handbuch/{self.repo}/k{chapter:02d}{suffix}.md"

    def target(self, url: str, base: str, lang: str, manual: bool) -> str:
        """The link `url` of a file in `base` (a directory of the repository), for the page in `lang`."""
        if re.match(r"^[a-z]+:", url) or url.startswith("//") or url.startswith("@/"):
            return url
        path, _, anchor = url.partition("#")
        if not path:
            if not manual:
                return url
            return self.anchor_link(lang, anchor)
        resolved = posixpath.normpath(posixpath.join(base, path))
        suffix = "" if lang == "de" else ".en"
        if resolved in ("docs/manual/de.md", "docs/manual/en.md"):
            return self.anchor_link(resolved[-5:-3], anchor)
        if resolved in ("CHANGELOG.md", "CHANGELOG.en.md"):
            other = "" if resolved == "CHANGELOG.md" else ".en"
            return f"@/aenderungen/{self.repo}{other}.md" + (f"#{anchor}" if anchor else "")
        if resolved in ("README.md", "README.en.md"):
            return f"@/{self.repo}{'' if resolved == 'README.md' else '.en'}.md"
        if manual and resolved.startswith("docs/manual/") and re.search(r"\.(jpe?g|png|webp|gif|svg)$", resolved):
            name = resolved[len("docs/manual/"):]
            return f"/handbuch-bilder/{self.repo}/{name}"
        kind = "tree" if path.endswith("/") else "blob"
        return f"{GITHUB}/{self.repo}/{kind}/{self.tag}/{resolved}" + (f"#{anchor}" if anchor else "")

    def anchor_link(self, lang: str, anchor: str) -> str:
        m = self.manuals[lang]
        if not anchor:
            return self.page(lang, 0)
        chapter = m.chapter_of.get(anchor)
        if chapter is None:
            return self.page(lang, 0)
        start_anchors = {m.anchor_of[s] for s in m.starts}
        # A chapter's own heading is the page title, which carries no anchor of its own in the content.
        if anchor in start_anchors:
            return self.page(lang, chapter)
        return self.page(lang, chapter) + f"#{anchor}"

    def rewrite(self, lines: list[str], indices: list[int], anchor_of: dict[int, str], base: str, lang: str,
                manual: bool, shift: int) -> str:
        out = []
        in_code = False
        for i in indices:
            line = lines[i]
            if FENCE.match(line):
                in_code = not in_code
                out.append(line)
                continue
            if in_code:
                out.append(line)
                continue
            m = HEADING.match(line)
            if m and i in anchor_of:
                level = max(2, len(m[1]) - shift)
                line = f"{'#' * level} {m[2]} {{#{anchor_of[i]}}}"
            line = MD_LINK.sub(lambda x: x[1] + self.target(x[2], base, lang, manual) + x[3], line)
            line = HTML_LINK.sub(lambda x: x[1] + self.html_target(x[2], base, lang, manual) + x[3], line)
            out.append(line)
        return "\n".join(out).strip() + "\n"

    def html_target(self, url: str, base: str, lang: str, manual: bool) -> str:
        """HTML attributes take no @/ links: images keep their site path, other links go to GitHub."""
        t = self.target(url, base, lang, manual)
        if t.startswith("@/"):
            return f"{GITHUB}/{self.repo}/blob/{self.tag}/{posixpath.normpath(posixpath.join(base, url.partition('#')[0]))}"
        return t

    def write(self) -> None:
        out = self.content / "handbuch" / self.repo
        out.mkdir(parents=True, exist_ok=True)
        de, en = (self.manuals[lang] for lang in LANGS)
        if len(de.starts) != len(en.starts):
            sys.exit(f"{self.repo}: {len(de.starts)} German and {len(en.starts)} English chapters")
        for lang in LANGS:
            m = self.manuals[lang]
            suffix = "" if lang == "de" else ".en"
            body = self.rewrite(m.lines, m.intro(), m.anchor_of, "docs/manual", lang, True, 0)
            (out / f"_index{suffix}.md").write_text(
                front(m.title, "manual-index.html", self.repo, self.tag, weight=None, sort=True) + body,
                encoding="utf-8",
            )
            for k, (title, anchor, indices) in enumerate(m.chapters(), start=1):
                body = self.rewrite(m.lines, indices, m.anchor_of, "docs/manual", lang, True, 1)
                number, _, text = title.partition(". ")
                if not number.isdigit():
                    number, text = str(k), title
                (out / f"k{k:02d}{suffix}.md").write_text(
                    front(text, "manual.html", self.repo, self.tag, weight=k, slug_=anchor, number=number) + body,
                    encoding="utf-8",
                )
        images = [d for d in ("images", "img") if (self.checkout / "docs/manual" / d).is_dir()]
        for d in images:
            target = self.static / "handbuch-bilder" / self.repo / d
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(self.checkout / "docs/manual" / d, target)
        changes = self.content / "aenderungen"
        changes.mkdir(parents=True, exist_ok=True)
        for lang, name in (("de", "CHANGELOG.md"), ("en", "CHANGELOG.en.md")):
            lines = (self.checkout / name).read_text(encoding="utf-8").splitlines()
            anchor_of = anchors(lines)
            first = next((i for i in range(1, len(lines)) if lines[i].startswith("## ")), len(lines))
            keep = [i for i in range(1, len(lines)) if i >= first or not lines[i].startswith("[")]
            body = self.rewrite(lines, keep, anchor_of, "", lang, False, 0)
            suffix = "" if lang == "de" else ".en"
            title = self.repo
            (changes / f"{self.repo}{suffix}.md").write_text(
                front(title, "changelog.html", self.repo, self.tag, weight=None), encoding="utf-8"
            )
            with open(changes / f"{self.repo}{suffix}.md", "a", encoding="utf-8") as f:
                f.write(body)


def front(title: str, template: str, repo: str, tag: str, weight, slug_: str | None = None, sort: bool = False,
          number: str | None = None) -> str:
    lines = ["+++", f"title = {toml(title)}", f'template = "{template}"']
    if weight is not None:
        lines.append(f"weight = {weight}")
    if slug_:
        lines.append(f"slug = {toml(slug_)}")
    if sort:
        lines.append('sort_by = "weight"')
    lines += ["", "[extra]", f'repo = "{repo}"', f'tag = "{tag}"']
    if number:
        lines.append(f'number = "{number}"')
    lines += ["+++", ""]
    return "\n".join(lines)


def toml(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    checkout, repo, tag, content, static = sys.argv[1:6]
    Docs(Path(checkout), repo, tag, Path(content), Path(static)).write()
    print(f"{repo} {tag}: manual and changelog")
